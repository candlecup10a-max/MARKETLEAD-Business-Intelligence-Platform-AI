// Helper to look up country by code or name
export function findCountry(query?: string): Country | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  if (q === 'all' || q === 'all countries' || q === 'all 249 countries' || q === '') {
    return undefined;
  }

  // 1. Exact 2-letter ISO code match
  const exactCode = COUNTRIES.find((c) => c.code.toLowerCase() === q);
  if (exactCode) return exactCode;

  // 2. Exact country name match
  const exactName = COUNTRIES.find((c) => c.name.toLowerCase() === q);
  if (exactName) return exactName;

  // 3. Match code inside parentheses e.g. "Tokyo (JP)" or "Austin, TX (US)"
  const codeInParen = query.match(/\(([A-Za-z]{2})\)/);
  if (codeInParen) {
    const fromParen = COUNTRIES.find((c) => c.code.toLowerCase() === codeInParen[1].toLowerCase());
    if (fromParen) return fromParen;
  }

  // 4. Match full country name contained in location string (e.g. "Munich, Germany" -> Germany)
  const containingCountry = COUNTRIES.find((c) => {
    const cName = c.name.toLowerCase();
    // Use word boundary check or comma check to avoid false substrings
    return q.includes(cName) && cName.length > 3;
  });
  if (containingCountry) return containingCountry;

  // 5. Query contains at least 4 characters and country name starts with or equals query
  if (q.length >= 4) {
    const startsWith = COUNTRIES.find((c) => c.name.toLowerCase().startsWith(q));
    if (startsWith) return startsWith;
  }

  return undefined;
}

